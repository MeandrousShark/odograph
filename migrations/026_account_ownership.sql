CREATE TABLE instance_state (
    id smallint PRIMARY KEY CHECK (id = 1),
    first_account_id bigint REFERENCES accounts(id) ON DELETE RESTRICT,
    bootstrap_completed_at timestamptz,
    legacy_config_imported_at timestamptz,
    security_contract_version text NOT NULL DEFAULT 'ownership-prepared-v1'
        CHECK (security_contract_version = 'ownership-prepared-v1'),
    CHECK ((first_account_id IS NULL) = (bootstrap_completed_at IS NULL))
);
INSERT INTO instance_state (id, first_account_id, bootstrap_completed_at)
SELECT 1, (SELECT id FROM accounts), (SELECT created_at FROM accounts);

CREATE TABLE tracking_devices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    label text NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    generation bigint NOT NULL DEFAULT 1 CHECK (generation > 0),
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (account_id, id)
);
CREATE TABLE tracking_device_aliases (
    account_id bigint NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    original_label text NOT NULL,
    tracking_device_id bigint NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    PRIMARY KEY (account_id, original_label),
    FOREIGN KEY (account_id, tracking_device_id)
        REFERENCES tracking_devices(account_id, id) ON DELETE RESTRICT
);
CREATE TABLE ingest_credentials (
    public_id text PRIMARY KEY,
    basic_username text NOT NULL UNIQUE,
    secret_hash text NOT NULL,
    account_id bigint NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    tracking_device_id bigint,
    kind text NOT NULL CHECK (kind IN ('legacy', 'device')),
    generation bigint NOT NULL DEFAULT 1 CHECK (generation > 0),
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (account_id, tracking_device_id)
        REFERENCES tracking_devices(account_id, id) ON DELETE RESTRICT,
    CHECK ((kind = 'legacy') = (tracking_device_id IS NULL))
);
CREATE INDEX ingest_credentials_account_device_idx
    ON ingest_credentials (account_id, tracking_device_id);

