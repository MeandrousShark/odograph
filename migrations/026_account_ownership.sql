CREATE TEMP TABLE ownership_legacy_checkpoint ON COMMIT DROP AS
SELECT last_run_at, detector_version FROM detector_state;
DROP TABLE detector_state;
CREATE TABLE detector_state (
    account_id bigint NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    tracking_device_id bigint PRIMARY KEY,
    last_run_at timestamptz,
    detector_version int NOT NULL DEFAULT 0,
    FOREIGN KEY (account_id, tracking_device_id)
        REFERENCES tracking_devices(account_id, id) ON DELETE RESTRICT
);

-- Canonical empty-instance seeds become defaults only after an account exists.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM accounts) THEN
        DELETE FROM tag_rules;
        DELETE FROM vehicles;
        DELETE FROM mileage_rates;
    END IF;
END $$;

DO $$
DECLARE table_name text;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'raw_messages', 'points', 'stays', 'trips', 'places', 'tag_rules',
        'geocode_cache', 'trip_boundary_overrides', 'vehicles',
        'odometer_readings', 'expenses', 'mileage_rates',
        'nudge_delivery_windows', 'odometer_reminder_windows', 'email_deliveries'
    ] LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN account_id bigint', table_name);
        EXECUTE format('UPDATE %I SET account_id = (SELECT id FROM accounts)', table_name);
        EXECUTE format('ALTER TABLE %I ALTER COLUMN account_id SET NOT NULL', table_name);
        EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE',
                       table_name, table_name || '_account_id_fkey');
    END LOOP;
END $$;

