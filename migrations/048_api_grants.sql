-- migration-class: additive
-- Revocable API grants: one per signed-in app installation. Tokens are
-- opaque and stored only as SHA-256 digests. The current generation holds the
-- live access and refresh pair; the previous generation keeps the pair it
-- replaced so an in-flight access token keeps working until it expires and a
-- dropped refresh response can be retried briefly. Every grant stops working
-- when its account's auth_version changes or the account is disabled.
-- Grants are authentication metadata, not account data: they are not charged
-- to storage and have no admission trigger, like email_challenges.
CREATE TABLE public.api_grants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES public.accounts(id) ON DELETE CASCADE,
    public_id text NOT NULL UNIQUE CHECK (public_id ~ '^[A-Za-z0-9_-]{22}$'),
    device_label text NOT NULL CHECK (device_label <> '' AND char_length(device_label) <= 64),
    issued_auth_version bigint NOT NULL CHECK (issued_auth_version > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    last_used_at timestamptz,
    revoked_at timestamptz,
    generation bigint NOT NULL DEFAULT 1 CHECK (generation > 0),
    access_digest text NOT NULL UNIQUE CHECK (access_digest ~ '^[0-9a-f]{64}$'),
    refresh_digest text NOT NULL UNIQUE CHECK (refresh_digest ~ '^[0-9a-f]{64}$'),
    access_expires_at timestamptz NOT NULL,
    current_seen boolean NOT NULL DEFAULT false,
    previous_access_digest text UNIQUE CHECK (previous_access_digest ~ '^[0-9a-f]{64}$'),
    previous_refresh_digest text UNIQUE CHECK (previous_refresh_digest ~ '^[0-9a-f]{64}$'),
    previous_access_expires_at timestamptz,
    rotated_at timestamptz,
    CHECK ((previous_access_digest IS NULL AND previous_refresh_digest IS NULL
            AND previous_access_expires_at IS NULL AND rotated_at IS NULL)
        OR (previous_access_digest IS NOT NULL AND previous_refresh_digest IS NOT NULL
            AND previous_access_expires_at IS NOT NULL AND rotated_at IS NOT NULL))
);
CREATE INDEX api_grants_account_idx ON public.api_grants (account_id);

-- Runtime has an account policy for defense in depth but no table grant;
-- control reaches grants only through the functions below.
ALTER TABLE public.api_grants ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.api_grants FORCE ROW LEVEL SECURITY;

-- Lifetimes: access tokens last 15 minutes. A grant idle-expires 60 days
-- after the later of its creation and its last use. A grant is active while
-- it is not revoked, not idle-expired and issued at the account's current
-- auth_version; any other grant can never authenticate again and is deleted
-- here. At most 10 active grants per account; a sign-in that replaces one of
-- them is net zero.
CREATE FUNCTION public.api_grant_create(
    input_account_id bigint, input_auth_version bigint, input_public_id text,
    input_device_label text, input_access_digest text, input_refresh_digest text,
    input_replaces text
) RETURNS TABLE (result text, result_access_expires_at timestamptz)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp
AS $body$
DECLARE
    account_row public.accounts%ROWTYPE;
    checked_at timestamptz;
    replaced_id bigint;
    active_count bigint;
BEGIN
    IF input_account_id IS NULL OR input_auth_version IS NULL
       OR input_public_id IS NULL OR input_public_id !~ '^[A-Za-z0-9_-]{22}$'
       OR input_device_label IS NULL OR input_device_label = ''
       OR pg_catalog.char_length(input_device_label) > 64
       OR input_access_digest IS NULL OR input_access_digest !~ '^[0-9a-f]{64}$'
       OR input_refresh_digest IS NULL OR input_refresh_digest !~ '^[0-9a-f]{64}$'
       OR input_access_digest = input_refresh_digest THEN
        RETURN QUERY SELECT 'unavailable'::text, NULL::timestamptz;
        RETURN;
    END IF;
    -- Serializes grant creation with auth_version changes without blocking
    -- foreign key checks on the account row.
    SELECT * INTO account_row FROM public.accounts a WHERE a.id = input_account_id FOR NO KEY UPDATE;
    IF NOT FOUND OR NOT account_row.is_enabled OR account_row.auth_version <> input_auth_version THEN
        RETURN QUERY SELECT 'unavailable'::text, NULL::timestamptz;
        RETURN;
    END IF;
    checked_at := pg_catalog.clock_timestamp();
    DELETE FROM public.api_grants g
    WHERE g.account_id = input_account_id
      AND (g.revoked_at IS NOT NULL
           OR g.issued_auth_version <> account_row.auth_version
           OR GREATEST(g.created_at, COALESCE(g.last_used_at, g.created_at))
              <= checked_at - interval '60 days');
    -- Every remaining grant of the account is active.
    IF input_replaces IS NOT NULL THEN
        SELECT g.id INTO replaced_id FROM public.api_grants g
        WHERE g.account_id = input_account_id AND g.public_id = input_replaces
        FOR UPDATE;
    END IF;
    SELECT pg_catalog.count(*) INTO active_count FROM public.api_grants g
    WHERE g.account_id = input_account_id;
    IF active_count - (CASE WHEN replaced_id IS NULL THEN 0 ELSE 1 END) >= 10 THEN
        RETURN QUERY SELECT 'grant_limit_reached'::text, NULL::timestamptz;
        RETURN;
    END IF;
    IF replaced_id IS NOT NULL THEN
        UPDATE public.api_grants g SET revoked_at = checked_at WHERE g.id = replaced_id;
    END IF;
    INSERT INTO public.api_grants
        (account_id, public_id, device_label, issued_auth_version, created_at,
         access_digest, refresh_digest, access_expires_at)
    VALUES (input_account_id, input_public_id, input_device_label, account_row.auth_version,
            checked_at, input_access_digest, input_refresh_digest,
            checked_at + interval '15 minutes');
    RETURN QUERY SELECT 'created'::text, checked_at + interval '15 minutes';
END
$body$;

-- Refresh rotation, retry and reuse under the grant row lock. The account row
-- is read but not locked, so this never waits on an account lock while
-- holding a grant lock (grant creation locks the account first).
CREATE FUNCTION public.api_grant_refresh(
    input_refresh_digest text, input_access_digest text, input_new_refresh_digest text
) RETURNS TABLE (result text, result_public_id text, result_access_expires_at timestamptz)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp
AS $body$
DECLARE
    grant_id bigint;
    grant_row public.api_grants%ROWTYPE;
    checked_at timestamptz;
    matched_current boolean;
BEGIN
    IF input_refresh_digest IS NULL OR input_refresh_digest !~ '^[0-9a-f]{64}$'
       OR input_access_digest IS NULL OR input_access_digest !~ '^[0-9a-f]{64}$'
       OR input_new_refresh_digest IS NULL OR input_new_refresh_digest !~ '^[0-9a-f]{64}$'
       OR input_access_digest = input_new_refresh_digest THEN
        RETURN QUERY SELECT 'invalid_grant'::text, NULL::text, NULL::timestamptz;
        RETURN;
    END IF;
    SELECT g.id INTO grant_id FROM public.api_grants g
    WHERE g.refresh_digest = input_refresh_digest OR g.previous_refresh_digest = input_refresh_digest;
    IF NOT FOUND THEN
        RETURN QUERY SELECT 'invalid_grant'::text, NULL::text, NULL::timestamptz;
        RETURN;
    END IF;
    -- A concurrent refresh may rotate the row while this one waits, so the
    -- match is decided again on the locked row.
    SELECT * INTO grant_row FROM public.api_grants g WHERE g.id = grant_id FOR UPDATE;
    IF NOT FOUND THEN
        RETURN QUERY SELECT 'invalid_grant'::text, NULL::text, NULL::timestamptz;
        RETURN;
    END IF;
    checked_at := pg_catalog.clock_timestamp();
    IF grant_row.revoked_at IS NOT NULL
       OR GREATEST(grant_row.created_at, COALESCE(grant_row.last_used_at, grant_row.created_at))
          <= checked_at - interval '60 days'
       OR NOT EXISTS (SELECT 1 FROM public.accounts a
                      WHERE a.id = grant_row.account_id AND a.is_enabled
                        AND a.auth_version = grant_row.issued_auth_version) THEN
        RETURN QUERY SELECT 'invalid_grant'::text, NULL::text, NULL::timestamptz;
        RETURN;
    END IF;
    IF grant_row.refresh_digest = input_refresh_digest THEN
        matched_current := true;
    ELSIF grant_row.previous_refresh_digest = input_refresh_digest THEN
        matched_current := false;
    ELSE
        RETURN QUERY SELECT 'invalid_grant'::text, NULL::text, NULL::timestamptz;
        RETURN;
    END IF;
    IF matched_current THEN
        UPDATE public.api_grants g SET
            previous_access_digest = g.access_digest,
            previous_refresh_digest = g.refresh_digest,
            previous_access_expires_at = g.access_expires_at,
            rotated_at = checked_at,
            access_digest = input_access_digest,
            refresh_digest = input_new_refresh_digest,
            access_expires_at = checked_at + interval '15 minutes',
            generation = g.generation + 1,
            current_seen = false,
            last_used_at = checked_at
        WHERE g.id = grant_row.id;
        RETURN QUERY SELECT 'rotated'::text, grant_row.public_id, checked_at + interval '15 minutes';
        RETURN;
    END IF;
    IF grant_row.current_seen THEN
        -- Two parties have held this grant. Revoke it and record the event.
        UPDATE public.api_grants g SET revoked_at = checked_at WHERE g.id = grant_row.id;
        INSERT INTO public.account_security_audit
            (occurred_at, actor_account_id, target_account_id, action, outcome)
        VALUES (checked_at, grant_row.account_id, grant_row.account_id,
                'api_grant_refresh_reuse', 'revoked');
        RETURN QUERY SELECT 'reuse_revoked'::text, grant_row.public_id, NULL::timestamptz;
        RETURN;
    END IF;
    IF grant_row.rotated_at > checked_at - interval '60 seconds' THEN
        -- Retry after a dropped response: replace the unseen current pair.
        -- The previous pair and rotated_at stay, so retries never extend the window.
        UPDATE public.api_grants g SET
            access_digest = input_access_digest,
            refresh_digest = input_new_refresh_digest,
            access_expires_at = checked_at + interval '15 minutes',
            last_used_at = checked_at
        WHERE g.id = grant_row.id;
        RETURN QUERY SELECT 'retried'::text, grant_row.public_id, checked_at + interval '15 minutes';
        RETURN;
    END IF;
    RETURN QUERY SELECT 'invalid_grant'::text, NULL::text, NULL::timestamptz;
END
$body$;

-- Bearer check. Accepts the current access token or the previous one until
-- its own expiry. Writes last_used_at at most once a minute and marks the
-- current generation seen once; otherwise it only reads. The result is
-- 'valid', 'unknown' when no grant holds the digest, or 'invalid' when one
-- does but cannot authenticate (expired, revoked, idle, stale version or
-- disabled account), so callers can tell guessing from an outdated token.
CREATE FUNCTION public.api_grant_authenticate(input_access_digest text)
RETURNS TABLE (result text, result_account_id bigint, result_auth_version bigint, result_public_id text)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp
AS $body$
DECLARE
    grant_row public.api_grants%ROWTYPE;
    checked_at timestamptz;
    matched_current boolean;
    mark_seen boolean;
    mark_used boolean;
BEGIN
    IF input_access_digest IS NULL OR input_access_digest !~ '^[0-9a-f]{64}$' THEN
        RETURN QUERY SELECT 'unknown'::text, NULL::bigint, NULL::bigint, NULL::text;
        RETURN;
    END IF;
    SELECT * INTO grant_row FROM public.api_grants g
    WHERE g.access_digest = input_access_digest OR g.previous_access_digest = input_access_digest;
    IF NOT FOUND THEN
        RETURN QUERY SELECT 'unknown'::text, NULL::bigint, NULL::bigint, NULL::text;
        RETURN;
    END IF;
    checked_at := pg_catalog.clock_timestamp();
    matched_current := grant_row.access_digest = input_access_digest;
    IF (matched_current AND NOT grant_row.current_seen)
       OR grant_row.last_used_at IS NULL
       OR grant_row.last_used_at <= checked_at - interval '1 minute' THEN
        -- Writing: decide again on the locked row, which a refresh may have rotated.
        SELECT * INTO grant_row FROM public.api_grants g WHERE g.id = grant_row.id FOR UPDATE;
        IF NOT FOUND THEN
            RETURN QUERY SELECT 'invalid'::text, NULL::bigint, NULL::bigint, NULL::text;
            RETURN;
        END IF;
        checked_at := pg_catalog.clock_timestamp();
        IF grant_row.access_digest = input_access_digest THEN
            matched_current := true;
        ELSIF grant_row.previous_access_digest = input_access_digest THEN
            matched_current := false;
        ELSE
            RETURN QUERY SELECT 'invalid'::text, NULL::bigint, NULL::bigint, NULL::text;
            RETURN;
        END IF;
    END IF;
    IF grant_row.revoked_at IS NOT NULL
       OR GREATEST(grant_row.created_at, COALESCE(grant_row.last_used_at, grant_row.created_at))
          <= checked_at - interval '60 days'
       OR (matched_current AND grant_row.access_expires_at <= checked_at)
       OR (NOT matched_current AND grant_row.previous_access_expires_at <= checked_at)
       OR NOT EXISTS (SELECT 1 FROM public.accounts a
                      WHERE a.id = grant_row.account_id AND a.is_enabled
                        AND a.auth_version = grant_row.issued_auth_version) THEN
        RETURN QUERY SELECT 'invalid'::text, NULL::bigint, NULL::bigint, NULL::text;
        RETURN;
    END IF;
    mark_seen := matched_current AND NOT grant_row.current_seen;
    mark_used := grant_row.last_used_at IS NULL OR grant_row.last_used_at <= checked_at - interval '1 minute';
    IF mark_seen OR mark_used THEN
        UPDATE public.api_grants g SET
            current_seen = g.current_seen OR mark_seen,
            last_used_at = CASE WHEN mark_used THEN checked_at ELSE g.last_used_at END
        WHERE g.id = grant_row.id;
    END IF;
    RETURN QUERY SELECT 'valid'::text, grant_row.account_id, grant_row.issued_auth_version, grant_row.public_id;
END
$body$;

-- Revocation sets revoked_at once and is never undone.
CREATE FUNCTION public.api_grant_revoke(input_account_id bigint, input_public_id text)
RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp
AS $body$
BEGIN
    UPDATE public.api_grants g SET revoked_at = pg_catalog.clock_timestamp()
    WHERE g.account_id = input_account_id AND g.public_id = input_public_id
      AND g.revoked_at IS NULL;
    RETURN FOUND;
END
$body$;

