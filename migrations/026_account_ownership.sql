INSERT INTO tracking_devices (account_id, label)
SELECT a.id, streams.device FROM accounts a CROSS JOIN (
    SELECT device FROM points
    UNION SELECT device FROM stays
    UNION SELECT device FROM trips WHERE source = 'detected' AND NOT imported
    UNION SELECT device FROM trip_boundary_overrides
) streams ORDER BY streams.device;
INSERT INTO tracking_device_aliases (account_id, original_label, tracking_device_id)
SELECT account_id, label, id FROM tracking_devices;
INSERT INTO detector_state (account_id, tracking_device_id, last_run_at, detector_version)
SELECT d.account_id, d.id, s.last_run_at, s.detector_version
FROM tracking_devices d CROSS JOIN ownership_legacy_checkpoint s;

UPDATE points p SET tracking_device_id = d.id FROM tracking_devices d
WHERE p.account_id = d.account_id AND p.device = d.label;
UPDATE stays s SET tracking_device_id = d.id FROM tracking_devices d
WHERE s.account_id = d.account_id AND s.device = d.label;
UPDATE trips t SET tracking_device_id = d.id FROM tracking_devices d
WHERE t.account_id = d.account_id AND t.device = d.label
    AND t.source = 'detected' AND NOT t.imported;
UPDATE trip_boundary_overrides o SET tracking_device_id = d.id FROM tracking_devices d
WHERE o.account_id = d.account_id AND o.device = d.label;
ALTER TABLE points ALTER COLUMN tracking_device_id SET NOT NULL;
ALTER TABLE stays ALTER COLUMN tracking_device_id SET NOT NULL;
ALTER TABLE trip_boundary_overrides ALTER COLUMN tracking_device_id SET NOT NULL;
ALTER TABLE trips ADD CONSTRAINT trips_detected_device_check
    CHECK (source <> 'detected' OR imported OR tracking_device_id IS NOT NULL);

