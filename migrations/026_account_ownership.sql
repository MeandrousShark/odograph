CREATE TABLE reference_mileage_rates (
    year int PRIMARY KEY,
    rate_per_mi numeric NOT NULL CHECK (rate_per_mi > 0),
    rate_h2_per_mi numeric CHECK (rate_h2_per_mi > 0),
    h2_start_month smallint CHECK (h2_start_month BETWEEN 1 AND 12),
    CHECK ((rate_h2_per_mi IS NULL) = (h2_start_month IS NULL))
);
